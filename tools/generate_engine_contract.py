#!/usr/bin/env python3
"""Render the reviewed shared argument/layout contract; never reads game files."""
import argparse,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def render():
    c=json.loads((ROOT/'tools/engine_contract.json').read_text())
    rows=[]
    for key,variants in c['cue_args'].items():
        game,fn=key.split(':')
        for a in variants:rows.append('{"%s",%s,{%s}}'%(game,fn,','.join(map(str,a))))
    return '''// Generated by tools/generate_engine_contract.py; do not hand edit.
#pragma once
#include "cuefns.hpp"
#include "gtf_cues.hpp"
#include <cstring>
namespace groove {
struct ArgProfile { const char* game; uint32_t fn; int a[4]; };
inline constexpr ArgProfile kArgProfiles[] = {
'''+',\n'.join(rows)+'''
};
inline bool validCueArgs(int game, uint32_t fn, const int* a) {
    if (game<0 || game>=kGameNames) return false;
    if (!strcmp(kGameName[game],"RING") && fn==0x217960)
        return a[0]>=-1 && a[0]<=15 && (a[1]==0 || a[1]==1) && a[2]==0 && a[3]==0;
    for (const auto& p:kArgProfiles)
        if (p.fn==fn && !strcmp(p.game,kGameName[game]) && !memcmp(p.a,a,4*sizeof(int))) return true;
    return false;
}
inline bool validLayout(int game, int layout) { return layout>=0 && layout==gtfcat::layoutOff(game); }
}
'''
def main():
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
    dest=ROOT/'engine/src/cue_validation.hpp';text=render()
    if a.check:
        if dest.read_text()!=text:raise SystemExit('Regenerate engine/src/cue_validation.hpp')
    else:dest.write_text(text)
if __name__=='__main__':main()
